/**
 * سطر — تحصين استدعاءات git ضد إعداد المستودع المُنفِّذ (‏OBS-136).
 *
 * **العطل**: `.git/config` **جزء من المستودع نفسه**، وفيه مفاتيح يشغّل git برنامجاً
 * مسمّى فيها — لا يقرؤه فحسب. فمستودعٌ يصل المستخدمَ ملفاتٍ ومعه مجلد `.git` (‏zip ·
 * قرص مشترك · USB — لا `git clone`) ينفّذ ما فيه **بمجرّد** أن يشغّل «سطر» أمر git
 * ليعرف أين هو. و«افتح مجلداً» هو الفعل الأول في «سطر».
 *
 * وهذه فئة **غير** التي تحرسها كتلة الأمان في `gitactions.js`: تلك تمنع حقن الوسائط
 * (‏`execFile` بمصفوفة، بلا shell، فاصل `--`، والمسار مُتحقَّق منه مقابل `git status`
 * الحيّة) — سليمة، ولا تمسّ هذه لأن التنفيذ يقع **داخل git** لا في الصدفة.
 *
 * **العلاج**: `-c <key>=<value>` قبل الأمر الفرعي يغلب ملف الإعداد، فيُبطل المفتاح
 * قبل أن يُقرأ. والقائمة مغلقة ومحصورة بما نستدعيه فعلاً:
 *
 *   - `core.fsmonitor` — يُنفَّذ عند `status` و`diff` وأي تحديث للفهرس. وهو الناقل
 *     المسمّى في بحث Manifold Security (‏2026-09-01)، ورُقّع في Claude Code 2.1.196.
 *     يُبطَل بـ`-c core.fsmonitor=false` (مقيس: آمن ولا يكسر أمراً).
 *   - `diff.external` — يُنفَّذ عند `git diff`، و`gitdiff.js` يشغّله على كل ملف متغيّر.
 *     يُبطَل بعلم الأمر **`--no-ext-diff`** لا بـ`-c`.
 *
 * **والتصميم مصحَّح بالقياس مرتين** (‏git `2.50.1.windows.1`):
 *   1. `-c diff.external=` **يكسر `git diff` برمز 128** — القيمة الفارغة تُقرأ «أمرٌ
 *      خارجي فارغ» لا «بلا أمر». فالعلم `--no-ext-diff` هو الصواب، وهو يُدرَج بعد
 *      الأمر الفرعي لأنه علم أمرٍ لا إعداد عام.
 *   2. `core.pager` أُسقط كلياً: المسبار أثبت أنه **لا يقع** مع `execFile` (بلا tty)،
 *      وإدراجه بـ`cat` كسر `test:reviewchanges` لأن `cat` ليس أمراً على ويندوز خارج
 *      Git Bash. **حمايةٌ لا تُقاس قد تكسر أكثر مما تحمي.**
 *
 * ⚠️ **ما لا تحرسه هذه الوحدة — مُصرَّح به**:
 *   - **`.git/hooks/`**: `git commit` يشغّلها، و`gitactions.commit` يستدعيه. لم تُعطَّل
 *     عمداً لأن hooks جزء من سير عمل المستخدم (‏`pre-commit` وأخواته) وتعطيلها يغيّر
 *     سلوكاً مقصوداً. من يفتح مستودعاً غير موثوق **ولا يلتزم فيه** لا يشغّلها.
 *   - **`filter.*.clean/smudge`**: تُنفَّذ عند `checkout`/`diff`، وتعطيلها يكسر Git LFS
 *     وهو شائع. الخطر أقل مباشرةً (يلزمها `.gitattributes` مطابق).
 *   - **`core.sshCommand` و`core.gitProxy`**: مسارات شبكة، ولا استدعاء شبكي في
 *     الملفات الخمسة.
 *
 * وحدة نقية بلا اعتماديات (نمط `execguard.js` و`browserguard.js`).
 */

'use strict';

/**
 * المفاتيح المُبطَلة. مغلقة عمداً: كل إضافة تحتاج مبرراً مكتوباً هنا، وكل قيمة
 * فارغة/`false` تعني «لا برنامج» لا «الافتراضي».
 */
const SAFE_CONFIG = Object.freeze([
  'core.fsmonitor=false',
]);

/** الأوامر التي تقبل `--no-ext-diff` (وهي نفسها التي تستدعي `diff.external`). */
const EXT_DIFF_COMMANDS = Object.freeze(['diff', 'log', 'show']);

/**
 * يبني وسائط git محصَّنة:
 *   - `-c` تسبق الأمر الفرعي وجوباً — git يتجاهلها بعده.
 *   - `--no-ext-diff` يلي الأمر الفرعي لأنه علم أمرٍ لا إعداد عام.
 *
 * لا تُطبَّق إلا على مصفوفة؛ أي مدخل آخر يعود كما هو كي لا تُخفي الوحدةُ خطأ استدعاء.
 */
function gitArgs(args) {
  if (!Array.isArray(args)) return args;
  const out = [];
  for (const entry of SAFE_CONFIG) out.push('-c', entry);
  out.push(...args);
  if (EXT_DIFF_COMMANDS.includes(args[0])) {
    // بعد الأمر الفرعي مباشرةً: git يقبل العلم في أي موضع بعده، وهذا أوضح للقارئ.
    out.splice(out.length - args.length + 1, 0, '--no-ext-diff');
  }
  return out;
}

module.exports = { gitArgs, SAFE_CONFIG, EXT_DIFF_COMMANDS };
