// عائلة أخطاء الحساب: إعادة المحاولة عديمة الجدوى فيها حتى يتصرّف المستخدم في حسابه.
// تُستعمل كي لا يُعرض «سنعيد المحاولة» فوق سببٍ لن يزول بإعادة محاولة.
const ACCOUNT_CODES = new Set([
  'authentication_failed',
  'oauth_org_not_allowed',
  'account_on_hold',
  'verification_required',
  'billing_error',
  'cloud_credential_error',
]);

/**
 * يصنّف رمز خطأ محرّك. يعيد null لغير المعروف (بما فيه غير النصّ) — فلا نخترع نصّاً
 * عربياً لرمزٍ لا نعرف دلالته.
 */
function classify(code) {
  if (typeof code !== 'string') return null;
  const message = ENGINE_ERROR_TEXT[code];
  if (!message) return null;
  return { code, message, account: ACCOUNT_CODES.has(code) };
}

module.exports = { classify, ACCOUNT_CODES, CODES: Object.keys(ENGINE_ERROR_TEXT) };
